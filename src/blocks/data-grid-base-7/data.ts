export function windowDays(moduleRecord: ProjectModule) {
  const start = new Date(moduleRecord.dateStart)
  const end = new Date(moduleRecord.dateEnd)
  return Math.round((end.getTime() - start.getTime()) / 86_400_000) + 1
}
