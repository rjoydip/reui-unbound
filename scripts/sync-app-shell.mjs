#!/usr/bin/env node
// Regenerate src/blocks/application/app-shell/~blocks.tsx from implemented folders.
import fs from "node:fs"
import path from "node:path"

const root = process.cwd()
const category = "App Shell"
const dir = "src/blocks/application/app-shell"
const manifest = JSON.parse(
  fs.readFileSync("src/blocks/application/~manifest.json", "utf8"),
)

function packageName(specifier) {
  if (
    specifier.startsWith(".") ||
    specifier.startsWith("@/") ||
    specifier.startsWith("node:")
  )
    return null
  if (["react", "react-dom", "react/jsx-runtime"].includes(specifier)) return null
  return specifier.startsWith("@")
    ? specifier.split("/").slice(0, 2).join("/")
    : specifier.split("/")[0]
}

function registryDep(specifier) {
  if (specifier.startsWith("@/components/ui/"))
    return specifier.slice("@/components/ui/".length).split("/")[0]
  if (specifier.startsWith("@/components/kit/base/ui/"))
    return (
      "@reui-unbound/base-ui-" +
      specifier.slice("@/components/kit/base/ui/".length).split("/")[0]
    )
  if (specifier.startsWith("@/components/kit/base/"))
    return (
      "@reui-unbound/base-" +
      specifier
        .slice("@/components/kit/base/".length)
        .split("/")[0]
        .replace(/\.tsx?$/, "")
    )
  if (specifier.startsWith("@/components/kit/"))
    return (
      "@reui-unbound/" +
      specifier
        .slice("@/components/kit/".length)
        .split("/")[0]
        .replace(/\.tsx?$/, "")
    )
  if (specifier.startsWith("@/hooks/"))
    return (
      "@reui-unbound/" +
      specifier.slice("@/hooks/".length).split("/")[0].replace(/\.tsx?$/, "")
    )
  return null
}

const slugs = fs
  .readdirSync(path.join(root, dir), { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && /^app-shell-\d+$/.test(entry.name))
  .map((entry) => entry.name)
  .sort((a, b) => Number(a.split("-").pop()) - Number(b.split("-").pop()))

const entries = []
for (const slug of slugs) {
  const meta = manifest.find((item) => item.slug === slug)
  if (!meta) {
    console.warn(`sync: no manifest entry for ${slug}`)
    continue
  }
  const file = `${dir}/${slug}/index.tsx`
  const source = fs.readFileSync(path.join(root, file), "utf8")
  const registry = new Set()
  const packages = new Set()
  for (const match of source.matchAll(/from\s+["']([^"']+)["']/g)) {
    const pkg = packageName(match[1])
    if (pkg) packages.add(pkg)
    const dep = registryDep(match[1])
    if (dep) registry.add(dep)
  }
  const exportName = `AppShell${slug.split("-").pop()}Block`
  entries.push({ slug, meta, registry: [...registry].sort(), packages: [...packages].sort(), exportName })
}

const imports = entries
  .map(
    (entry) =>
      `import ${entry.exportName} from "@/blocks/application/app-shell/${entry.slug}"`,
  )
  .join("\n")
const rawImports = entries
  .map(
    (entry) =>
      `import ${entry.exportName}Source from "@/blocks/application/app-shell/${entry.slug}/index.tsx?raw"`,
  )
  .join("\n")

const items = entries
  .map(
    (entry) => `  {
    id: "${entry.slug}",
    name: ${JSON.stringify(entry.meta.title)},
    category: ${JSON.stringify(category)},
    stage: "Application",
    group: "application",
    href: ${JSON.stringify(entry.meta.url)},
    installTarget: "@reui-unbound/${entry.slug}",
    dependencies: {
      registry: ${JSON.stringify(entry.registry)},
      packages: ${JSON.stringify(entry.packages)},
    },
    Component: ${entry.exportName},
    files: [file("index.tsx", ${entry.exportName}Source, "tsx")],
  },`,
  )
  .join("\n")

const output = `// Generated by scripts/sync-app-shell.mjs. Do not edit.
import type { BlockEntry } from "@/blocks/~internal/registry"

${imports}

${rawImports}

const file = (name: string, code: string, lang: "tsx" | "typescript" = "tsx") => ({
  name,
  code,
  lang,
})

export const APP_SHELL_BLOCKS: BlockEntry[] = [
${items}
]
`

fs.writeFileSync(path.join(root, `${dir}/~blocks.tsx`), output)
console.log(`sync: ${entries.length} app shell blocks written to ${dir}/~blocks.tsx`)
